"""Build a deterministic, fail-closed Agents Squad 2.0 file manifest.

O que é: scanner read-only e serializador de proveniência file-by-file.
Responsabilidade: classificar cada arquivo capturado exatamente uma vez e
falhar diante de path, hash, symlink, executável ou reconciliação inválidos.
Pra que serve: fundamentar uma distribuição limpa sem copiar work histórico.
Comportamento em falha: não grava outputs até toda a árvore ser validada.
Conexões: contracts/distribution-file.schema.json e distribution/*.json*.
"""

